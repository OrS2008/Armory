// Regenerates src/fonts.gen.ts from public/fonts (run: node scripts/embed-fonts.cjs).
// The fonts are served by the Worker itself, so no static-assets upload is needed.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'public', 'fonts');
const out = ['// GENERATED by scripts/embed-fonts.cjs. Do not edit.', '// Fonts: SIL Open Font License 1.1 (see the LICENSE-*.txt entries).', 'export const FONT_FILES: Record<string, string> = {'];
for (const f of fs.readdirSync(dir).sort()) out.push(`  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString('base64'))},`);
out.push('};', '');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'fonts.gen.ts'), out.join('\n'));
console.log('ok', fs.readdirSync(dir).length);
