"""Builds src/areas.gen.ts: outlines of the main Area A cities (Palestinian Authority
control; Israelis are barred from entering by military order, marked by red signs).
Source: OpenStreetMap boundaries via Nominatim (one request per city, run rarely, by hand).
Usage: python3 -I scripts/area-a.py"""
import json, sys, time, urllib.parse, urllib.request, os

CITIES = ['Jenin', 'Qabatiya', 'Tubas', 'Nablus', 'Tulkarm', 'Qalqilya', 'Salfit', 'Ramallah', 'Al-Bireh',
          'Jericho', 'Bethlehem', 'Beit Jala', 'Beit Sahour', 'Hebron', 'Halhul', 'Dura', 'Yatta']
UA = 'HeyNav/1.0 (+https://heynav.ors2008.workers.dev)'


def fetch(city):
    q = urllib.parse.urlencode({'city': city, 'countrycodes': 'ps', 'format': 'jsonv2', 'polygon_geojson': 1,
                                'polygon_threshold': 0.0008, 'limit': 1})
    req = urllib.request.Request('https://nominatim.openstreetmap.org/search?' + q, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def rings(geo):
    t, c = geo['type'], geo['coordinates']
    if t == 'Polygon':
        return [c[0]]
    if t == 'MultiPolygon':
        return [p[0] for p in c]
    return []


out = []
for city in CITIES:
    hits = fetch(city)
    time.sleep(1.2)  # Nominatim policy: at most one request per second
    if not hits or hits[0].get('geojson', {}).get('type') not in ('Polygon', 'MultiPolygon'):
        print('skip (no outline):', city, file=sys.stderr)
        continue
    for ring in rings(hits[0]['geojson']):
        out.append({'name': city, 'ring': [[round(x, 5), round(y, 5)] for x, y in ring]})
    print('ok', city, sum(len(r) for r in rings(hits[0]['geojson'])), file=sys.stderr)

root = os.path.join(os.path.dirname(__file__), '..')
with open(os.path.join(root, 'src', 'areas.gen.ts'), 'w') as f:
    f.write('// GENERATED by scripts/area-a.py from OpenStreetMap (© OpenStreetMap contributors, ODbL).\n')
    f.write('// Main Area A cities: Israelis are barred from entering by military order.\n')
    f.write('export const AREA_A: { name: string; ring: [number, number][] }[] = ')
    f.write(json.dumps(out, ensure_ascii=False))
    f.write(';\n')
print(len(out), 'outlines', file=sys.stderr)
