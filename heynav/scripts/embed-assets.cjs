// Regenerates src/assets.gen.ts (git-ignored): MapLibre GL and the fonts, served by the Worker itself.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const ml = path.join(root, 'node_modules', 'maplibre-gl', 'dist');
const files = {
  'vendor/maplibre-gl.mjs': [path.join(ml, 'maplibre-gl.mjs'), 'text/javascript; charset=utf-8'],
  'vendor/maplibre-gl-worker.mjs': [path.join(ml, 'maplibre-gl-worker.mjs'), 'text/javascript; charset=utf-8'],
  'vendor/maplibre-gl.css': [path.join(ml, 'maplibre-gl.css'), 'text/css; charset=utf-8'],
  'vendor/LICENSE-maplibre.txt': [path.join(root, 'node_modules', 'maplibre-gl', 'LICENSE.txt'), 'text/plain; charset=utf-8'],
};
for (const f of fs.readdirSync(path.join(root, 'public', 'fonts')))
  files['fonts/' + f] = [path.join(root, 'public', 'fonts', f), f.endsWith('.woff2') ? 'font/woff2' : 'text/plain; charset=utf-8'];
const out = ['// GENERATED by scripts/embed-assets.cjs. Do not edit; not committed.', 'export const ASSETS: Record<string, { type: string; text?: string; b64?: string }> = {'];
for (const [k, [p, type]] of Object.entries(files)) {
  const buf = fs.readFileSync(p);
  const bin = type.startsWith('font/');
  out.push(`  ${JSON.stringify(k)}: { type: ${JSON.stringify(type)}, ${bin ? 'b64' : 'text'}: ${JSON.stringify(bin ? buf.toString('base64') : buf.toString('utf8'))} },`);
}
out.push('};', '');
fs.writeFileSync(path.join(root, 'src', 'assets.gen.ts'), out.join('\n'));
console.log('assets:', Object.keys(files).length);
